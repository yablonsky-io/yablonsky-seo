<?php
namespace Yablonsky\PerformanceSEO\Discovery;

use Yablonsky\PerformanceSEO\SEO\Sitemap\SitemapXml;

if ( ! defined( 'ABSPATH' ) ) { exit; }

/** Google Merchant-compatible RSS 2.0 serialization of the neutral commerce dataset. */
final class CommerceFeedSerializer {
    /** @var ProductFeedRepository */ private $repository;
    public function __construct( ProductFeedRepository $repository ) { $this->repository = $repository; }

    /** @param resource $handle @return array{products:int,bytes:int} */
    public function write( $handle ): array {
        $bytes = 0; $products = 0;
        $write = static function ( $handle, string $value ) use ( &$bytes ): void {
            // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_fwrite -- Deliberate bounded streaming into an atomic local feed snapshot.
            $written = fwrite( $handle, $value ); if ( false !== $written ) { $bytes += $written; }
        };
        $write( $handle, '<?xml version="1.0" encoding="UTF-8"?>' . "\n" );
        $write( $handle, '<rss xmlns:g="http://base.google.com/ns/1.0" version="2.0"><channel>' . "\n" );
        $write( $handle, '<title>' . SitemapXml::text( (string) get_bloginfo( 'name' ) . ' Commerce Feed' ) . '</title>' . "\n" );
        $write( $handle, '<link>' . SitemapXml::url( home_url( '/' ) ) . '</link>' . "\n" );
        $write( $handle, '<description>' . SitemapXml::text( 'Commerce product data generated by Yablonsky SEO.' ) . '</description>' . "\n" );
        $cursor = 0;
        do {
            $rows = $this->repository->pageAfter( $cursor, 500 );
            foreach ( $rows as $row ) {
                $cursor = max( $cursor, (int) ( $row['product_id'] ?? 0 ) );
                $payload = json_decode( (string) ( $row['payload'] ?? '' ), true );
                if ( ! is_array( $payload ) ) { continue; }
                $item = $this->itemXml( $payload );
                if ( '' === $item ) { continue; }
                $write( $handle, $item ); $products++;
            }
        } while ( count( $rows ) === 500 );
        $write( $handle, "</channel></rss>\n" );
        return array( 'products' => $products, 'bytes' => $bytes );
    }

    /** @param array<string,mixed> $row */
    private function itemXml( array $row ): string {
        $identity = isset( $row['identity'] ) && is_array( $row['identity'] ) ? $row['identity'] : array();
        $content = isset( $row['content'] ) && is_array( $row['content'] ) ? $row['content'] : array();
        $media = isset( $row['media'] ) && is_array( $row['media'] ) ? $row['media'] : array();
        $commerce = isset( $row['commerce'] ) && is_array( $row['commerce'] ) ? $row['commerce'] : array();
        $classification = isset( $row['classification'] ) && is_array( $row['classification'] ) ? $row['classification'] : array();
        $required = array(
            'id' => (string) ( $identity['id'] ?? '' ), 'title' => (string) ( $content['title'] ?? '' ),
            'description' => (string) ( $content['description'] ?? '' ), 'link' => (string) ( $content['link'] ?? '' ),
            'image_link' => (string) ( $media['primary_image'] ?? '' ), 'availability' => (string) ( $commerce['availability'] ?? '' ),
            'price' => $this->money( (string) ( $commerce['price'] ?? '' ), (string) ( $commerce['currency'] ?? '' ) ),
            'condition' => (string) ( $commerce['condition'] ?? 'new' ),
        );
        foreach ( $required as $value ) { if ( '' === trim( (string) $value ) ) { return ''; } }
        $xml = '<item>';
        foreach ( $required as $field => $value ) { $xml .= '<g:' . $field . '>' . $this->fieldValue( $field, $value ) . '</g:' . $field . '>'; }
        $settings = new DiscoverySettings();
        if ( $settings->commerceFieldEnabled( 'sale_price' ) ) { $sale = $this->money( (string) ( $commerce['sale_price'] ?? '' ), (string) ( $commerce['currency'] ?? '' ) ); if ( '' !== $sale ) { $xml .= '<g:sale_price>' . SitemapXml::text( $sale ) . '</g:sale_price>'; } }
        $optional = array( 'brand' => (string) ( $classification['brand'] ?? '' ), 'gtin' => (string) ( $identity['gtin'] ?? '' ), 'mpn' => (string) ( $identity['mpn'] ?? '' ), 'product_type' => (string) ( $classification['product_type'] ?? '' ) );
        foreach ( $optional as $field => $value ) { if ( $settings->commerceFieldEnabled( $field ) && '' !== trim( $value ) ) { $xml .= '<g:' . $field . '>' . SitemapXml::text( $value ) . '</g:' . $field . '>'; } }
        if ( $settings->commerceFieldEnabled( 'additional_images' ) && isset( $media['additional_images'] ) && is_array( $media['additional_images'] ) ) { foreach ( array_slice( $media['additional_images'], 0, 10 ) as $url ) { $xml .= '<g:additional_image_link>' . SitemapXml::url( (string) $url ) . '</g:additional_image_link>'; } }
        return $xml . "</item>\n";
    }

    private function money( string $amount, string $currency ): string { $amount = trim( $amount ); $currency = strtoupper( trim( $currency ) ); return '' === $amount || '' === $currency ? '' : $amount . ' ' . $currency; }
    private function fieldValue( string $field, string $value ): string { return in_array( $field, array( 'link', 'image_link' ), true ) ? SitemapXml::url( $value ) : SitemapXml::text( $value ); }
}
